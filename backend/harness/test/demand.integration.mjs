// Run inside an isolated test Space, with no provider credentials or inference.
import assert from 'node:assert/strict';
import { execFileSync, spawn } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';
const lib = '/usr/local/lib/metor';
const { resourceAlive } = await import(`${lib}/metor-desktop.mjs`);
const { readBot } = await import(`${lib}/metor-store.mjs`);
const name = 'demand-probe';
const cli = (...args) => execFileSync('metor', args, { encoding: 'utf8' });
cli('bot', 'create', name, '--harness', 'codex');
const state = () => JSON.parse(readFileSync(`/workspace/bots/${name}/.metor/harness.json`));
const alive = (kind) => resourceAlive(readBot(name), kind);
const wait = async (check) => { for (let i = 0; i < 200; i++) { if (await check()) return; await new Promise(r => setTimeout(r, 100)); } throw new Error('Timed out'); };
const link = cli('auth', 'link', '--plain').match(/http[^\s]+claim\?token=[A-Za-z0-9_-]+/)[0];
const claim = await fetch(link, { redirect: 'manual' });
const cookie = claim.headers.get('set-cookie').split(';')[0];
const req = (path, method = 'GET') => fetch(`http://127.0.0.1:6010/bots/${path}`, { method, headers: { cookie } });
assert.equal(state().runtimeLoaded, false);
for (const kind of ['browser', 'desktop', 'terminal']) assert.equal(alive(kind), false);
await req('api/harnesses');
await req(`api/agents/${name}/chat/commands`);
await req(`api/agents/${name}/files`);
assert.equal(state().runtimeLoaded, false);
assert.equal(alive('browser'), false);
console.log('PASS: create, lists, files and command polling keep the runtime and computer unloaded');
assert.equal((await req(`${name}/terminal/`)).status, 200);
assert.ok(alive('terminal')); assert.equal(alive('browser'), false);
assert.equal(state().runtimeLoaded, false);
console.log('PASS: terminal starts without browser, desktop or runtime');
const b = readBot(name);
const mcp = spawn('node', [`${lib}/metor-browser-mcp.mjs`, name, '--cdp-endpoint', `http://127.0.0.1:${9200 + b.display}`], { stdio: ['pipe', 'pipe', 'inherit'] });
let seq = 0, buf = ''; const pending = new Map();
mcp.stdout.on('data', d => { buf += d; let at; while ((at = buf.indexOf('\n')) >= 0) { const line = buf.slice(0, at); buf = buf.slice(at + 1); const m = JSON.parse(line); pending.get(m.id)?.(m); pending.delete(m.id); } });
const rpc = (method, params) => new Promise((resolve, reject) => { const id = ++seq; const timer = setTimeout(() => reject(new Error(`Timeout: ${method}`)), 65000); pending.set(id, m => { clearTimeout(timer); resolve(m); }); mcp.stdin.write(JSON.stringify({ jsonrpc: '2.0', id, method, params }) + '\n'); });
try {
  await rpc('initialize', { protocolVersion: '2024-11-05', clientInfo: { name: 'metor-demand-test', version: '1' }, capabilities: {} });
  mcp.stdin.write(JSON.stringify({ jsonrpc: '2.0', method: 'notifications/initialized' }) + '\n');
  const tools = await rpc('tools/list', {});
  assert.ok(tools.result.tools.some(t => t.name === 'browser_tabs'));
  assert.equal(alive('browser'), false);
  const tabs = await rpc('tools/call', { name: 'browser_tabs', arguments: { action: 'list' } });
  assert.ok(!tabs.error && !tabs.result.isError, JSON.stringify(tabs));
  assert.ok(alive('browser')); assert.equal(alive('desktop'), false);
  assert.equal(state().runtimeLoaded, false);
  console.log('PASS: MCP discovery stays light; the first browser tool starts Chromium');
  const pid = readFileSync(`/workspace/bots/${name}/.desktop/chromium.pid`, 'utf8');
  const screens = await Promise.all([req(`${name}/vnc.html`), req(`${name}/vnc.html`)]);
  assert.ok(screens.every(r => r.status === 200)); assert.ok(alive('desktop'));
  assert.equal(readFileSync(`/workspace/bots/${name}/.desktop/chromium.pid`, 'utf8'), pid);
  console.log('PASS: concurrent Screen requests reuse the browser and start the desktop');
  await req(`api/agents/${name}/chat/commands`, 'POST');
  await wait(() => state().capabilities?.models?.length);
  assert.equal(state().runtimeLoaded, true);
  const ps = execFileSync('ps', ['-eo', 'args'], { encoding: 'utf8' });
  assert.match(ps, /codex app-server/); assert.doesNotMatch(ps, /gemini --acp|copilot --acp|claude --output-format/);
  console.log('PASS: explicit slash discovery activates only the selected runtime');
} finally { mcp.kill('SIGTERM'); }
cli('bot', 'stop', name); cli('bot', 'start', name);
assert.equal(state().runtimeLoaded, false);
for (const kind of ['browser', 'desktop', 'terminal']) assert.equal(alive(kind), false);
assert.ok(existsSync(`/workspace/bots/${name}/.browser`));
console.log('PASS: Stop/Start returns to lightweight mode and preserves the browser profile');
cli('bot', 'rm', name);
