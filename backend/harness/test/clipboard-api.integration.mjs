// Run inside an isolated Space with a running smoke bot on display 11. Never run against a personal bot.
import { chromium } from '/usr/local/lib/node_modules/@playwright/mcp/node_modules/playwright/index.mjs';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
const base='http://127.0.0.1:6010';
const link=execFileSync('metor',['auth','link','--plain'],{encoding:'utf8'}).match(/http[^\s]+claim\?token=[A-Za-z0-9_-]+/)[0];
const signed=await fetch(link,{redirect:'manual'});
const cookie=signed.headers.get('set-cookie').split(';')[0];
const endpoint=base+'/bots/api/agents/smoke/screen-paste';
const request=(body,headers={})=>fetch(endpoint,{method:'POST',headers:{cookie,'content-type':'application/json',...headers},body:JSON.stringify(body)});
const browser=await chromium.connectOverCDP('http://127.0.0.1:9211');
const page=await browser.contexts()[0].newPage();
await page.setContent('<form onsubmit="window.submitted=true;return false"><textarea autofocus></textarea><button>Submit</button></form>');
await page.bringToFront();await page.locator('textarea').focus();
const text='Grüße 👋 中文\n$(touch /tmp/metor-paste-must-not-exist)\n`echo hi`';
const result=await request({text});assert.equal(result.status,200,await result.text());
await page.waitForFunction(value=>document.querySelector('textarea').value===value,text);
assert.equal(await page.evaluate(()=>!!window.submitted),false);
assert.equal(await page.locator('textarea').inputValue(),text);
console.log('PASS: Unicode, multiline and shell-like text pasted exactly into Chromium; form not submitted');
assert.equal((await request({text:123})).status,400);
assert.equal((await request({text:'a'.repeat(262145)})).status,400);
assert.equal((await request({text:'x'},{origin:'https://untrusted.example'})).status,403);
assert.equal((await fetch(endpoint,{method:'POST',headers:{'content-type':'application/json'},body:'{"text":"x"}'})).status,401);
const screen=await (await fetch(base+'/bots/smoke/vnc.html',{headers:{cookie}})).text();
assert.ok(screen.includes('<script src="/bots/screen-clipboard.js"></script>'));
assert.equal((await fetch(base+'/bots/screen-clipboard.js',{headers:{cookie}})).status,200);
console.log('PASS: endpoint validation, authentication, origin protection and Screen integration');
await page.close(); await browser.close();
